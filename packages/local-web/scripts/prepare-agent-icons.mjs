import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";

// Keep this catalog and generator identical in Core and Cloud. Only output
// paths differ. Chart titles/colors preserve the existing Cloud grouping.
const brands = [
  ["codex", "OpenAI", "000000", "codex"],
  ["openai", "OpenAI", "000000", "openai|gpt"],
  ["claude", "Claude", "D97757", "claude|anthropic"],
  ["gemini", "Google Gemini", "8E75B2", "gemini"],
  ["githubcopilot", "GitHub Copilot", "000000", "copilot"],
  ["cursor", "Cursor", "000000", "cursor"],
  ["opencode", "OpenCode", "000000", "open[-_ ]?code"],
  ["docker", "Docker", "2496ED", "docker"],
  ["windsurf", "Windsurf", "0B100F", "windsurf"],
  ["zed", "Zed Industries", "084CCF", "zed"],
  ["cline", "Cline", "000000", "cline"],
  ["roocode", "Roo Code", "000000", "^roo(?:[-_ ]?code)?$"],
  ["goose", "Goose", "000000", "goose"],
  ["trae", "TRAE", "32F08C", "trae"],
  ["deepseek", "DeepSeek", "4D6BFE", "deepseek"],
  ["kimi", "Kimi", "000000", "kimi"],
  ["qwen", "Qwen", "615CED", "qwen"],
  ["grok", "Grok", "000000", "grok"],
  ["amp", "Amp", "EF4434", "^amp$"],
  ["antigravity", "Antigravity", "4285F4", "antigravity"],
  ["kilocode", "Kilo Code", "000000", "kilo[-_ ]?code"],
];
const require = createRequire(import.meta.url);
const packageRoot = path.dirname(require.resolve("@lobehub/icons-static-svg/package.json"));
const [spriteFile, catalogFile] = process.argv.slice(2);
if (!spriteFile || !catalogFile) throw new Error("Expected sprite and catalog output paths");
const symbols = [], catalog = [];
for (const [key, title, hex, match] of brands) {
  let svg, variant;
  // Codex deliberately uses the monochrome OpenAI knot, not the colored app badge.
  const candidates = key === "codex" ? ["openai"] : [`${key}-color`, key];
  for (const candidate of candidates) {
    try {
      svg = await readFile(path.join(packageRoot, "icons", `${candidate}.svg`), "utf8");
      variant = candidate;
      break;
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }
  catalog.push({ key, title, hex, match, variant: variant ?? null });
  if (!svg) continue; // The renderer uses Lucide for unavailable brands.
  // Preserve fills, gradients and fill rules; strip intrinsic sizing so the
  // caller's existing dimensions continue to control the icon.
  let symbol = svg.replace(/^<svg\b([^>]*)>/, (_, attrs) =>
    `<symbol id="${key}"${attrs.replace(/\s(?:width|height|style|xmlns)="[^"]*"/g, "")}>`
  ).replace(/<\/svg>$/, "</symbol>").replace(/<title>.*?<\/title>/g, "");
  // Kimi's color asset uses a white letter intended for dark backgrounds.
  // Keep its blue accent; let only that neutral letter follow the theme.
  if (key === "kimi") symbol = symbol.replaceAll('fill="#fff"', 'fill="currentColor"');
  const ids = [...symbol.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]).filter((id) => id !== key);
  for (const id of ids) symbol = symbol.replaceAll(`"${id}"`, `"${key}-${id}"`).replaceAll(`#${id}`, `#${key}-${id}`);
  symbols.push(symbol);
}
const version = JSON.parse(await readFile(path.join(packageRoot, "package.json"), "utf8")).version;
for (const file of [spriteFile, catalogFile]) await mkdir(path.dirname(file), { recursive: true });
await writeFile(spriteFile, `<!-- Generated from @lobehub/icons-static-svg ${version} (MIT; see agent-icons.LICENSE.txt). Run icons:prepare. -->\n<svg xmlns="http://www.w3.org/2000/svg">${symbols.join("\n")}</svg>\n`);
await writeFile(catalogFile, `// Generated by icons:prepare; keep Core and Cloud in sync.\nexport const agentBrands = ${JSON.stringify(catalog, null, 2)} as const;\n`);
